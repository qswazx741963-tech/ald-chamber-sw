#!/usr/bin/env python3
"""
ALD Chamber Modbus 暫存器產生器

讀 shared/modbus/registers.yaml，產生：
  firmware/lib/AldRegisters/registers_<board>.h   (Arduino)
  ipc/src/Ald.Comm/Generated/Registers.g.cs        (C#)
  shared/modbus/register-map.md                    (給人看 / Modbus Poll 對照)

用法：
  python tools/codegen/gen_registers.py           產生檔案
  python tools/codegen/gen_registers.py --check   只檢查產生檔是否最新（CI 用）
"""
import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "shared/modbus/registers.yaml"
OUT_H_DIR = ROOT / "firmware/lib/AldRegisters"
OUT_CS = ROOT / "ipc/src/Ald.Comm/Generated/Registers.g.cs"
OUT_MD = ROOT / "shared/modbus/register-map.md"

BANNER = "自動產生，請勿手改。來源：shared/modbus/registers.yaml"
WIDTH = {"u16": 1, "i16": 1, "i32": 2}
AREAS = (("input", "IR", "Input Register (FC04)"), ("holding", "HR", "Holding Register (FC03/FC16)"))


# ---------------------------------------------------------------- 讀取與檢查
def load():
    data = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    errors = []
    for bname, board in data["boards"].items():
        for area, _, _ in AREAS:
            regs = data["common"].get(area, []) + board.get(area, [])
            used = {}
            names = set()
            for r in regs:
                r.setdefault("type", "u16")
                r.setdefault("count", 1)
                r.setdefault("scale", 1)
                if r["type"] not in WIDTH:
                    errors.append(f"{bname}.{r['name']}: 未知 type {r['type']}")
                    continue
                if r["name"] in names:
                    errors.append(f"{bname}.{area}: 名稱重複 {r['name']}")
                names.add(r["name"])
                if len(r.get("bits", [])) > 16:
                    errors.append(f"{bname}.{r['name']}: bits 超過 16 個")
                span = WIDTH[r["type"]] * r["count"]
                for a in range(r["addr"], r["addr"] + span):
                    if a in used:
                        errors.append(f"{bname}.{area}: 位址 {a} 重疊（{used[a]} 與 {r['name']}）")
                    used[a] = r["name"]
                r["span"] = span
    if errors:
        sys.exit("registers.yaml 有錯誤：\n  " + "\n  ".join(errors))
    return data


def regs_of(data, bname, area):
    return data["common"].get(area, []) + data["boards"][bname].get(area, [])


def pascal(name):
    return "".join(p.capitalize() for p in name.lower().split("_"))


def fmt_num(v):
    return repr(float(v)) if isinstance(v, float) or v != int(v) else str(int(v))


# ---------------------------------------------------------------- Arduino .h
def gen_h(data, bname):
    b = data["boards"][bname]
    L = [f"// {BANNER}", "#pragma once", "#include <stdint.h>", "",
         f"// {bname}: {b.get('desc', '')}", f"namespace reg {{", "",
         f"constexpr uint16_t MAP_VERSION_VALUE = {data['map_version']};",
         f"constexpr uint8_t  SLAVE_ID = {b['slave_id']};", ""]
    for area, prefix, title in AREAS:
        regs = regs_of(data, bname, area)
        size = max(r["addr"] + r["span"] for r in regs) if regs else 0
        L.append(f"// ---- {title}")
        L.append(f"constexpr uint16_t {prefix}_SIZE = {size};")
        for r in regs:
            n = f"{prefix}_{r['name']}"
            L.append(f"constexpr uint16_t {n} = {r['addr']};  // {r['type']}"
                     + (f" x{r['count']}" if r["count"] > 1 else "")
                     + (f" [{r['unit']}]" if "unit" in r else "")
                     + (f" scale {r['scale']}" if r["scale"] != 1 else ""))
            if r["count"] > 1:
                L.append(f"constexpr uint16_t {n}_COUNT = {r['count']};")
            if "min" in r:
                L.append(f"constexpr int32_t  {n}_MIN_RAW = {round(r['min'] / r['scale'])};")
            if "max" in r:
                L.append(f"constexpr int32_t  {n}_MAX_RAW = {round(r['max'] / r['scale'])};")
            for i, bit in enumerate(r.get("bits", [])):
                L.append(f"constexpr uint16_t {n}_BIT_{bit} = {i};")
            for k, v in r.get("values", {}).items():
                L.append(f"constexpr uint16_t {n}_{k} = {v};")
        L.append("")
    L += ["}  // namespace reg", ""]
    return "\n".join(L)


# ---------------------------------------------------------------- C#
def gen_cs(data):
    L = [f"// <auto-generated> {BANNER} </auto-generated>",
         "namespace Ald.Comm.Generated;", "",
         "public static class RegisterMap", "{",
         f"    public const ushort MapVersion = {data['map_version']};", "}", ""]
    for bname, b in data["boards"].items():
        cls = pascal(bname)
        L += [f"/// <summary>{b.get('desc', '')}</summary>",
              f"public static class {cls}", "{",
              f"    public const byte SlaveId = {b['slave_id']};",
              f"    public const string DefaultPort = \"{b.get('port', '')}\";", ""]
        for area, prefix, title in AREAS:
            regs = regs_of(data, bname, area)
            cname = "Input" if prefix == "IR" else "Holding"
            size = max(r["addr"] + r["span"] for r in regs) if regs else 0
            L += [f"    /// <summary>{title}</summary>", f"    public static class {cname}", "    {",
                  f"        public const ushort Size = {size};"]
            for r in regs:
                p = pascal(r["name"])
                doc = r.get("desc", "") + (f" [{r['unit']}]" if "unit" in r else "")
                if doc.strip():
                    L.append(f"        /// <summary>{doc.strip()}</summary>")
                L.append(f"        public const ushort {p} = {r['addr']};")
                if r["count"] > 1:
                    L.append(f"        public const ushort {p}Count = {r['count']};")
                if r["scale"] != 1:
                    L.append(f"        public const double {p}Scale = {fmt_num(r['scale'])};")
                if "min" in r:
                    L.append(f"        public const double {p}Min = {fmt_num(r['min'])};")
                if "max" in r:
                    L.append(f"        public const double {p}Max = {fmt_num(r['max'])};")
                if r.get("bits"):
                    L.append(f"        [System.Flags] public enum {p}Bits : ushort")
                    L.append("        {")
                    for i, bit in enumerate(r["bits"]):
                        L.append(f"            {pascal(bit)} = 1 << {i},")
                    L.append("        }")
                if r.get("values"):
                    L.append(f"        public enum {p}Values : ushort")
                    L.append("        {")
                    for k, v in r["values"].items():
                        L.append(f"            {pascal(k)} = {v},")
                    L.append("        }")
            L += ["    }", ""]
        L += ["}", ""]
    return "\n".join(L)


# ---------------------------------------------------------------- Markdown
def gen_md(data):
    L = [f"# Modbus 暫存器表（map_version {data['map_version']}）", "", f"> {BANNER}", ""]
    for bname, b in data["boards"].items():
        L += [f"## {bname}（Slave ID {b['slave_id']}，{b.get('port', '')}）", "", b.get("desc", ""), ""]
        for area, prefix, title in AREAS:
            L += [f"### {title}", "", "| 位址 | 名稱 | 型別 | 數量 | 倍率 | 單位 | 範圍 | 說明 |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
            for r in regs_of(data, bname, area):
                end = r["addr"] + r["span"] - 1
                addr = f"{r['addr']}" if end == r["addr"] else f"{r['addr']}–{end}"
                rng = f"{r.get('min', '')}–{r.get('max', '')}" if "min" in r or "max" in r else ""
                note = r.get("desc", "")
                if r.get("bits"):
                    note += " bits: " + ", ".join(f"{i}={x}" for i, x in enumerate(r["bits"]))
                if r.get("values"):
                    note += " 值: " + ", ".join(f"{v}={k}" for k, v in r["values"].items())
                L.append(f"| {prefix} {addr} | {r['name']} | {r['type']} | {r['count']} | "
                         f"{r['scale'] if r['scale'] != 1 else ''} | {r.get('unit', '')} | {rng} | {note.strip()} |")
            L.append("")
    return "\n".join(L)


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只檢查，不寫檔")
    args = ap.parse_args()

    data = load()
    outputs = {OUT_CS: gen_cs(data), OUT_MD: gen_md(data)}
    for bname in data["boards"]:
        outputs[OUT_H_DIR / f"registers_{bname}.h"] = gen_h(data, bname)

    stale = []
    for path, text in outputs.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path.relative_to(ROOT))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")

    if args.check:
        if stale:
            sys.exit("以下產生檔不是最新，請執行 gen_registers.py：\n  " + "\n  ".join(map(str, stale)))
        print("產生檔皆為最新")
    else:
        print(f"已更新 {len(stale)} 個檔案" if stale else "沒有變更")
        for p in stale:
            print("  ", p)


if __name__ == "__main__":
    main()
